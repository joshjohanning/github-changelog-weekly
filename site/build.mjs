#!/usr/bin/env node
// Builds a static GitHub Pages site from the weekly changelog summary issues.
// Usage: GITHUB_TOKEN=... GITHUB_REPOSITORY=owner/repo node site/build.mjs [outDir]

import { copyFile, mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = process.env.GITHUB_REPOSITORY || 'joshjohanning/github-changelog-weekly';
const token = process.env.GITHUB_TOKEN || process.env.GH_TOKEN;
const label = process.env.SITE_LABEL || 'changelog-summary';
const outDir = process.argv[2] || '_site';
const apiUrl = process.env.GITHUB_API_URL || 'https://api.github.com';
const serverUrl = process.env.GITHUB_SERVER_URL || 'https://github.com';
const siteTitle = 'GitHub Changelog Weekly';
const assetsDir = join(dirname(fileURLToPath(import.meta.url)), 'assets');
// Primer CSS 22 dropped Box/Header/etc.; 21.x still ships markdown-body, btn and utilities.
const primerCss = 'https://cdn.jsdelivr.net/npm/@primer/css@21.5.1/dist/primer.css';
const primitives = 'https://cdn.jsdelivr.net/npm/@primer/primitives@11.10.0/dist/css';

if (!token) {
  console.error('GITHUB_TOKEN (or GH_TOKEN) is required');
  process.exit(1);
}

async function api(path, init = {}) {
  const res = await fetch(`${apiUrl}${path}`, {
    ...init,
    headers: {
      Accept: 'application/vnd.github+json',
      Authorization: `Bearer ${token}`,
      'X-GitHub-Api-Version': '2022-11-28',
      ...init.headers,
    },
  });
  if (!res.ok) throw new Error(`${init.method || 'GET'} ${path} failed: ${res.status} ${await res.text()}`);
  return res;
}

async function listIssues() {
  const issues = [];
  for (let page = 1; ; page++) {
    const res = await api(
      `/repos/${repo}/issues?labels=${encodeURIComponent(label)}&state=all&per_page=100&page=${page}`,
    );
    const batch = await res.json();
    issues.push(...batch.filter((i) => !i.pull_request).map((i) => ({ ...i, body: i.body ?? '' })));
    if (batch.length < 100) break;
  }
  return issues.sort((a, b) => new Date(b.created_at) - new Date(a.created_at));
}

// Drop the gh-aw generated footer (run metadata, expiry, hidden markers).
function cleanBody(body = '') {
  const idx = body.search(/^> Generated by \[/m);
  return (idx === -1 ? body : body.slice(0, idx)).replace(/<!--[\s\S]*?-->/g, '').trimEnd();
}

async function renderMarkdown(text) {
  const res = await api('/markdown', {
    method: 'POST',
    body: JSON.stringify({ text, mode: 'gfm', context: repo }),
  });
  return res.text();
}

const esc = (s) =>
  String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

const decode = (s) =>
  s.replace(/&(amp|lt|gt|quot|#39);/g, (_, e) => ({ amp: '&', lt: '<', gt: '>', quot: '"', '#39': "'" })[e]);

const displayTitle = (t) => t.replace(/^\[Changelog\]\s*/, '').replace(/^Week of\s+/i, '');

const fmtDate = (d, opts = { year: 'numeric', month: 'short', day: 'numeric' }) =>
  new Date(d).toLocaleDateString('en-US', { ...opts, timeZone: 'UTC' });

const pad = (n) => String(n).padStart(2, '0');

function summaryLine(body = '') {
  const m = body.match(/^📊\s*(.+)$/m);
  return m ? m[1].replace(/\*\*/g, '') : '';
}

function highlights(body = '') {
  const section = body.split(/^## .*Top Highlights.*$/m)[1]?.split(/^## /m)[0] ?? '';
  return [...section.matchAll(/^### \[(.+?)\]\((.+?)\)\s*\n+`([^`]+)`/gm)]
    .map(([, title, url, tag]) => {
      try {
        const parsed = new URL(url);
        if (!['http:', 'https:'].includes(parsed.protocol)) return null;
        return { title: decode(title), url: parsed.href, tag };
      } catch {
        return null;
      }
    })
    .filter(Boolean);
}

