function weekCard(i, root, latest) {
  return `<a class="card" href="${root}weeks/${i.number}/">
  <span class="card-meta mono">${pad(i.week)} · ${fmtDate(i.created_at)}${latest ? '<span class="badge-latest">latest</span>' : ''}</span>
  <span class="card-title">${esc(displayTitle(i.title))}</span>
  <span class="card-stats">${esc(summaryLine(i.body))}</span>
  <span class="card-cta">Read week →</span>
</a>`;
}

function indexPage(issues) {
  const [latest] = issues;
  const tops = latest ? highlights(latest.body).slice(0, 6) : [];
  const terminal = latest
    ? `<section class="terminal" aria-label="Latest highlights">
  <div class="terminal-bar mono"><span class="terminal-dots"><span></span><span></span><span></span></span>changelog / latest</div>
  <div class="terminal-body mono">
    <p class="comment">// Top highlights · ${esc(displayTitle(latest.title))}</p>
    <ol>
      ${tops
        .map(
          (h, n) =>
            `<li><span class="num">${pad(n + 1)}</span><a href="${esc(h.url)}">${esc(h.title)}</a><span class="tag">${esc(h.tag)}</span></li>`,
        )
        .join('\n      ')}
    </ol>
  </div>
  <div class="terminal-foot mono"><a href="weeks/${latest.number}/">Read the full week</a><span aria-hidden="true">↗</span></div>
</section>`
    : '';

  return layout({
    title: siteTitle,
    description: "Weekly AI-written summaries of what's shipping on GitHub.",
    root: './',
    issues,
    content: `<p class="eyebrow mono">Weekly GitHub changelog digest</p>
<h1 class="hero-title">Everything GitHub shipped.<span class="accent">One read a week.</span></h1>
<p class="hero-lede">Top highlights, deprecations to watch, and a full reference table of every changelog entry — summarized each Monday. ${issues.length} weeks and counting.</p>
<div class="hero-actions">
  ${latest ? `<a class="btn btn-primary" href="weeks/${latest.number}/">Read the latest week →</a>` : ''}
  <a class="btn" href="https://github.blog/changelog/">GitHub Changelog ↗</a>
  <span class="status-dot">Updated every Monday</span>
</div>
${terminal}
<h2 class="section-title">All weeks</h2>
<div class="card-grid">
${issues.map((i, n) => weekCard(i, './', n === 0)).join('\n')}
</div>`,
  });
}

function weekPage(issue, html, issues, newer, older) {
  const pagerCard = (i, cls, label) =>
    i
      ? `<a class="card ${cls}" href="../${i.number}/"><span class="card-meta mono">${label}</span><span class="card-title">${esc(displayTitle(i.title))}</span></a>`
      : '';
  return layout({
    title: `${displayTitle(issue.title)} · ${siteTitle}`,
    description: summaryLine(issue.body) || `GitHub changelog summary for ${displayTitle(issue.title)}`,
    root: '../../',
    issues,
    currentNumber: issue.number,
    content: `<p class="eyebrow mono">Week ${pad(issue.week)}</p>
<h1 class="hero-title">${esc(displayTitle(issue.title))}</h1>
<p class="article-meta"><span>Published ${fmtDate(issue.created_at)}</span>
  <a href="${issue.html_url}">Discuss on issue #${issue.number} ↗</a></p>
<article class="article markdown-body">
${html}
</article>
<nav class="pager" aria-label="Week navigation">
  ${pagerCard(older, 'prev', '← Previous week')}
  ${pagerCard(newer, 'next', 'Next week →')}
</nav>`,
  });
}

const issues = await listIssues();
issues.forEach((i, idx) => (i.week = issues.length - idx));
console.log(`Found ${issues.length} issues labeled "${label}" in ${repo}`);

await rm(outDir, { recursive: true, force: true });
await mkdir(join(outDir, 'assets'), { recursive: true });
await writeFile(join(outDir, '.nojekyll'), '');
for (const f of await readdir(assetsDir)) await copyFile(join(assetsDir, f), join(outDir, 'assets', f));
await writeFile(join(outDir, 'index.html'), indexPage(issues));

for (const [idx, issue] of issues.entries()) {
  const html = await renderMarkdown(cleanBody(issue.body));
  const dir = join(outDir, 'weeks', String(issue.number));
  await mkdir(dir, { recursive: true });
  await writeFile(join(dir, 'index.html'), weekPage(issue, html, issues, issues[idx - 1], issues[idx + 1]));
}

console.log(`Wrote site to ${outDir}`);
