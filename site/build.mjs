function sidebar(issues, root, currentNumber) {
  let html = '';
  let month = '';
  for (const i of issues) {
    const m = fmtDate(i.created_at, { year: 'numeric', month: 'long' });
    if (m !== month) {
      html += `${month ? '</ol>' : ''}<p class="sidebar-month mono">${esc(m)}</p><ol>`;
      month = m;
    }
    const current = i.number === currentNumber ? ' aria-current="page"' : '';
    html += `<li><a href="${root}weeks/${i.number}/"${current}><span class="num mono">${pad(i.week)}</span><span>${esc(displayTitle(i.title))}</span></a></li>`;
  }
  return `<nav class="sidebar" aria-label="Weeks">
  <p class="sidebar-heading mono"><a href="${root}" style="all:unset;cursor:pointer">All weeks</a></p>
  ${html}</ol>
</nav>`;
}

